package com.okpay.plugin.sumapay.util;

import java.util.Set;

/**
 * 丰付 result 码分类（错误码表适配所有接口）。
 *
 * <p>只有明确业务失败码才允许 S_FAIL；系统内部异常、参数校验、配置缺失、渠道处理中、
 * 未知码一律 S_WAIT。退款接口的 00000/00001 仅表示“受理成功，正在处理”，不是成功。</p>
 */
public final class SumapayErrors {

    private SumapayErrors() {}

    /** 受理/处理中：结果未定，等通知/查询/人工。 */
    private static final Set<String> ACCEPTED = Set.of(
            "00000", "00001",
            "200300304", // 银行已受理
            "200300305",
            "200300437", // 交易正在退款中
            "200300438", // 系统结算中
            "310100198"  // 交易处理中
    );

    /**
     * 明确业务失败：渠道已明确拒绝/失败，可落失败终态。
     * 系统异常块、参数/配置错误、处理中/未知码不在此列。
     */
    private static final Set<String> EXPLICIT_FAILURE = Set.of(
            "110100002", // 原订单不存在
            "200300031", // 未找到订单
            "200300051", // 退款金额超过原订单金额
            "200300162", // 金额不足
            "200300163", // 商户垫付手续费账户余额不足
            "200300330", // 银行鉴权失败
            "200300363", // 交易超时被置为失败
            "200300377", // 无此交易
            "200300387", // 用户未签约/协议失效
            "200300390", // 不支持付款至信用卡
            "200300439", // 未结金额不足
            "310100102", // 余额不足
            "310100104", // 订单已关闭
            "310100106", // 超过微信退款期限
            "310100204", // 交易已关闭
            "310100217", // 卖家余额不足
            "310100218", // 退款金额超限
            "310100220", "310100227", "310100229", // 交易不存在
            "310100221", // 交易已完结
            "310100223", // 已退款成功，无法重复退款
            "310100224", // 退款金额无效
            "310100225", // 当前交易不允许退款
            "310100226", // 退款金额有误
            "310100230", // 买家不存在
            "400000002", // 不存在退款的原交易
            "400000008", // 超出退款期限
            "600100001", // 风控拒绝
            "600100003", // 风险用户审核拒绝
            "600100006"  // 风险银行卡审核拒绝
    );

    /** 受理/处理中/可稍后重试。 */
    public static boolean accepted(String result) {
        return result != null && ACCEPTED.contains(result);
    }

    /** 渠道明确业务失败。 */
    public static boolean explicitFailure(String result) {
        return result != null && EXPLICIT_FAILURE.contains(result);
    }
}
